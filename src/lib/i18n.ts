const DICTIONARIES: Record<LanguageMode, Partial<Record<keyof typeof en, string>>> = { en, ar, zh };

export type TranslationKey = keyof typeof en;

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => (key in vars ? String(vars[key]) : `{${key}}`));
}

/**
 * useT() returns a t(key, vars?) function bound to the current language
 * setting. A key missing from ar/zh falls back to English rather than
 * rendering blank, so a partially-translated addition never breaks the UI.
 */
export function useT() {
  const { language } = useSettings();
  const dict = DICTIONARIES[language];

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      const template = dict[key] ?? en[key] ?? key;
      return interpolate(template, vars);
    },
    [dict]
  );

  return useMemo(() => ({ t, language }), [t, language]);
}

type TFn = ReturnType<typeof useT>["t"];

// The four small helpers below translate a stored English enum value (the
// value actually saved in Supabase — status, priority, role, category)
// into a display label, without touching the stored value itself. Casting
// through TranslationKey is safe here because each dictionary key above
// was written to match its corresponding enum value exactly.
export function statusLabel(t: TFn, status: string): string {
  return t(`status.${status}` as TranslationKey);
}
export function priorityLabel(t: TFn, priority: string): string {
  return t(`priority.${priority}` as TranslationKey);
}
export function roleLabel(t: TFn, role: string): string {
  return t(`role.${role}` as TranslationKey);
}
export function categoryLabel(t: TFn, category: string): string {
  return t(`category.${category}` as TranslationKey);
}
